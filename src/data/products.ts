export function getCategoryById(categoryId: string): ProductCategory | undefined {
  return PRODUCT_CATEGORIES.find((cat) => cat.id === categoryId);
}

export function getProductById(productId: string): ProductOffer | undefined {
  return PRODUCT_OFFERS.find((prod) => prod.id === productId);
}

export function getOffersByCategory(categoryId: string): ProductOffer[] {
  return PRODUCT_OFFERS.filter((prod) => prod.categoryId === categoryId);
}
